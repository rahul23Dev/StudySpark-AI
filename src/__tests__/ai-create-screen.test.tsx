import { fireEvent, screen, waitFor } from '@testing-library/react-native';

import { AiClientError, generate, type FlashcardGeneration } from '@/ai/client';
import CreateWithAiScreen from '@/app/ai/create';

import { mockRouter, resetMockRouter } from '../../test/expo-router-mock';
import { openTestRepository } from '../../test/node-sqlite';
import { renderScreen } from '../../test/render';

jest.mock('expo-router', () => jest.requireActual('../../test/expo-router-mock'));
jest.mock('@/ai/client', () => ({
  ...jest.requireActual('@/ai/client'),
  generate: jest.fn(),
}));
const mockGenerate = jest.mocked(generate);

const generation: FlashcardGeneration = {
  kind: 'flashcards',
  aiGenerated: true,
  deck: {
    title: 'Photosynthesis basics',
    cards: [
      { question: 'What gas do plants absorb?', answer: 'Carbon dioxide', difficulty: 'easy' },
      { question: 'Where does photosynthesis happen?', answer: 'In chloroplasts', difficulty: 'medium' },
    ],
  },
  meta: { requestId: 'r', model: 'claude-opus-5-5', attempts: 1, usage: { inputTokens: 1, outputTokens: 1 } },
};

beforeEach(() => {
  resetMockRouter();
  mockGenerate.mockReset();
});

async function fillTopicAndGenerate(topic = 'Photosynthesis') {
  await fireEvent.changeText(screen.getByLabelText('Topic'), topic);
  await fireEvent.press(screen.getByRole('button', { name: 'Generate flashcards' }));
}

describe('Create with AI', () => {
  it('asks for a topic before sending anything', async () => {
    const { repo } = await openTestRepository();
    await renderScreen(<CreateWithAiScreen />, repo);
    await fireEvent.press(screen.getByRole('button', { name: 'Generate flashcards' }));
    expect(screen.getByText('Enter a topic to study.')).toBeTruthy();
    expect(mockGenerate).not.toHaveBeenCalled();
  });

  it('generates, shows a review clearly marked as AI, and saves it as a local deck', async () => {
    mockGenerate.mockResolvedValueOnce(generation);
    const { repo } = await openTestRepository();
    await renderScreen(<CreateWithAiScreen />, repo);
    await fireEvent.press(screen.getByRole('radio', { name: 'Hard' }));
    await fireEvent.press(screen.getByRole('radio', { name: '5' }));
    await fillTopicAndGenerate();

    expect(mockGenerate).toHaveBeenCalledWith(
      'flashcards',
      expect.objectContaining({ source: { type: 'topic', topic: 'Photosynthesis' }, difficulty: 'hard', count: 5 }),
      expect.objectContaining({ signal: expect.anything() }),
    );
    expect(await screen.findByText(/Generated by AI\. AI can make mistakes/)).toBeTruthy();
    expect(screen.getByText('What gas do plants absorb?')).toBeTruthy();

    await fireEvent.changeText(screen.getByLabelText('Deck title'), 'Plants');
    await fireEvent.press(screen.getByRole('button', { name: 'Save as deck' }));

    await waitFor(() => expect(mockRouter.replace).toHaveBeenCalled());
    const [deck] = await repo.listDecks();
    expect(deck).toMatchObject({ title: 'Plants', source: 'ai', cardCount: 2 });
    expect(mockRouter.replace).toHaveBeenCalledWith({ pathname: '/deck/[id]', params: { id: deck.id, created: '1' } });
  });

  it('shows a clear setup message when AI is not configured, and saves nothing', async () => {
    mockGenerate.mockRejectedValueOnce(
      new AiClientError('ai_not_configured', 'AI generation is not set up on the server yet. Add ANTHROPIC_API_KEY…', false, 503),
    );
    const { repo } = await openTestRepository();
    await repo.createDeck({ title: 'Existing deck' });
    await renderScreen(<CreateWithAiScreen />, repo);
    await fillTopicAndGenerate();

    expect(await screen.findByText('AI isn’t set up yet')).toBeTruthy();
    expect(screen.getByText(/ANTHROPIC_API_KEY/)).toBeTruthy();
    expect(screen.queryByRole('button', { name: 'Try again' })).toBeNull(); // not retryable
    expect((await repo.listDecks()).map((d) => d.title)).toEqual(['Existing deck']);
  });

  it('offers a retry for temporary failures and recovers', async () => {
    mockGenerate
      .mockRejectedValueOnce(new AiClientError('ai_timeout', 'The AI took too long to respond. Please try again.', true, 504))
      .mockResolvedValueOnce(generation);
    const { repo } = await openTestRepository();
    await renderScreen(<CreateWithAiScreen />, repo);
    await fillTopicAndGenerate();

    expect(await screen.findByText('The AI took too long to respond. Please try again.')).toBeTruthy();
    expect(screen.getByText('Your existing decks are safe. Nothing was saved.')).toBeTruthy();
    await fireEvent.press(screen.getByRole('button', { name: 'Try again' }));
    expect(await screen.findByText('What gas do plants absorb?')).toBeTruthy();
    expect(mockGenerate).toHaveBeenCalledTimes(2);
    expect(await repo.listDecks()).toEqual([]); // still nothing saved until "Save as deck"
  });

  it('switches to quiz options and notes input', async () => {
    const { repo } = await openTestRepository();
    await renderScreen(<CreateWithAiScreen />, repo);
    await fireEvent.press(screen.getByRole('radio', { name: 'Quiz' }));
    await fireEvent.press(screen.getByRole('radio', { name: 'My notes' }));
    expect(screen.getByLabelText('Your notes')).toBeTruthy();
    expect(screen.getByRole('radio', { name: 'True or false' })).toBeTruthy();
    await fireEvent.changeText(screen.getByLabelText('Your notes'), 'too short');
    await fireEvent.press(screen.getByRole('button', { name: 'Generate quiz' }));
    expect(screen.getByText('Paste at least 40 characters of notes.')).toBeTruthy();
    expect(mockGenerate).not.toHaveBeenCalled();
  });
});
